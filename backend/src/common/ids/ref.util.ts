/**
 * Human-readable reference numbers (REQ-022, BKG-004, DEAL-006).
 *
 * Format deliberately matches the prototype's `nextRef()` so refs already
 * visible in demo data stay consistent after the Phase 10 cutover.
 *
 * Production allocation uses PostgreSQL sequences (see the reference-sequences
 * migration), so it is O(1) and concurrency-safe. These formatting helpers
 * remain pure and reusable by seed/test code.
 */

/** "REQ", 22 -> "REQ-022" */
export function formatRef(prefix: string, n: number | bigint): string {
  return `${prefix}-${String(n).padStart(3, '0')}`;
}

/**
 * Retries a create on an exceptionally rare generated-identifier collision.
 * Sequence-backed refs should not collide, but capability tokens also have
 * unique indexes and are regenerated by each closure invocation.
 */
export async function retryOnUniqueViolation<T>(fn: () => Promise<T>, attempts = 3): Promise<T> {
  let lastError: unknown;
  for (let attempt = 0; attempt < attempts; attempt++) {
    try {
      return await fn();
    } catch (error) {
      if ((error as { code?: string }).code !== 'P2002') throw error;
      lastError = error;
    }
  }
  throw lastError;
}
